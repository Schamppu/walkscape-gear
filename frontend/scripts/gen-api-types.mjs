/**
 * Generates TypeScript types from the WalkScape Tools API OpenAPI spec.
 *
 * Usage: npm run gen:api-types [-- <spec url>]
 * Defaults to the locally running API.
 */
import fs from "node:fs";
import process from "node:process";
import openapiTS, { astToString } from "openapi-typescript";

const specUrl = process.argv[2] ?? "http://localhost:2999/docs/openapi.json";
const outFile = new URL(
  "../src/domain/types/generated/api.d.ts",
  import.meta.url,
);

const TYPE_KEYS = [
  "type",
  "$ref",
  "anyOf",
  "oneOf",
  "allOf",
  "enum",
  "properties",
  "items",
];

/**
 * zod-to-openapi emits `z.null()` (and the null half of `.nullable()` on a
 * union) as a schema with no type, only `nullable: true`. openapi-typescript
 * turns that into `unknown`, which also collapses any union it is part of to
 * `unknown`. Rewrite it as an explicit null type.
 */
function normalizeBareNullables(node) {
  if (Array.isArray(node)) {
    node.forEach(normalizeBareNullables);
    return;
  }
  if (!node || typeof node !== "object") return;

  if (node.nullable === true && !TYPE_KEYS.some((key) => key in node)) {
    delete node.nullable;
    node.type = "null";
    return;
  }
  Object.values(node).forEach(normalizeBareNullables);
}

const response = await fetch(specUrl);
if (!response.ok) {
  throw new Error(`Failed to fetch ${specUrl}: ${response.status}`);
}
const spec = await response.json();
normalizeBareNullables(spec);

const ast = await openapiTS(spec);

const header =
  "/**\n * This file was auto-generated by scripts/gen-api-types.mjs.\n * Do not make direct changes to the file.\n */\n\n";

fs.mkdirSync(new URL(".", outFile), { recursive: true });
fs.writeFileSync(outFile, header + astToString(ast));
console.log(`Wrote src/domain/types/generated/api.d.ts from ${specUrl}`);
